-- 1. MEVCUT VE YENİ TABLOLARA tenant_id KOLONU EKLEME VE İNDEKSLER

DO $$
DECLARE
    tbl text;
    tables text[] := ARRAY[
        'cariler',
        'stoklar',
        'stok_hareketler',
        'faturalar',
        'fatura_detaylar',
        'kasalar',
        'kasa_hareketler',
        'bankalar',
        'banka_hareketler',
        'siparisler',
        'siparis_detaylar',
        'teklifler',
        'teklif_detaylar',
        'notlar',
        'kullanicilar',
        'firma_profili'
    ];
BEGIN
    FOREACH tbl IN ARRAY tables LOOP
        IF EXISTS (SELECT FROM information_schema.tables WHERE table_schema = 'public' AND table_name = tbl) THEN
            EXECUTE format('ALTER TABLE public.%I ADD COLUMN IF NOT EXISTS tenant_id TEXT NOT NULL DEFAULT ''default'';', tbl);
            EXECUTE format('CREATE INDEX IF NOT EXISTS %I ON public.%I (tenant_id);', 'idx_' || tbl || '_tenant_id', tbl);
            EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY;', tbl);
            EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I;', tbl || '_tenant_policy', tbl);
            EXECUTE format('CREATE POLICY %I ON public.%I FOR ALL USING (true) WITH CHECK (true);', tbl || '_tenant_policy', tbl);
        END IF;
    END LOOP;
END $$;

-- 2. MALİ YILLAR TABLOSU (Çoklu Kiracı Destekli)
CREATE TABLE IF NOT EXISTS public.mali_yillar (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    yil INT NOT NULL,
    tenant_id TEXT NOT NULL DEFAULT 'default',
    is_active BOOLEAN DEFAULT TRUE,
    is_deleted BOOLEAN DEFAULT FALSE,
    olusturma_tarihi TIMESTAMPTZ DEFAULT NOW(),
    CONSTRAINT uq_mali_yillar_yil_tenant UNIQUE (yil, tenant_id)
);
CREATE INDEX IF NOT EXISTS idx_mali_yillar_tenant ON public.mali_yillar (tenant_id, is_deleted);
ALTER TABLE public.mali_yillar ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "mali_yillar_all_policy" ON public.mali_yillar;
CREATE POLICY "mali_yillar_all_policy" ON public.mali_yillar FOR ALL USING (true) WITH CHECK (true);

